<?php

namespace Tounaf\Exception\Handler\Generic;

use Psr\Log\LoggerInterface;
use Symfony\Component\ErrorHandler\Exception\FlattenException;
use Tounaf\Exception\Exception\ExceptionHandlerInterface;
use Symfony\Component\HttpFoundation\Response;
use Symfony\Component\HttpKernel\Exception\HttpExceptionInterface;
use Tounaf\Exception\Exception\DecoratorExceptionHandlerInterface;
use Tounaf\Exception\Exception\TounafException;

/**
 * Decorator exception handler that adds logging capabilities.
 *
 * This class wraps an existing `ExceptionHandlerInterface` instance and logs
 * the exception before delegating the actual handling to the wrapped handler.
 * It specifically logs `TounafException` instances but could be made more generic
 * by changing the `supportsException` logic.
 */
class GeneraleLoggerExceptionHandler implements DecoratorExceptionHandlerInterface
{
    /**
     * @var LoggerInterface The PSR-3 logger instance.
     */
    private $logger;

    /**
     * @var ExceptionHandlerInterface The decorated exception handler instance.
     */
    private ExceptionHandlerInterface $decoratedExceptionHandlerInterface;

    /**
     * GeneraleLoggerExceptionHandler constructor.
     *
     * @param LoggerInterface $logger The logger service to be used for logging exceptions.
     */
    public function __construct(LoggerInterface $logger)
    {
        $this->logger = $logger;
    }

    /**
     * Handles the exception by first logging it, then delegating to the decorated handler.
     *
     * It flattens the exception to get a consistent representation for logging.
     *
     * @param  \Throwable $throwable The exception or error to handle.
     * @return Response The HTTP response generated by the decorated handler.
     */
    public function handleException(\Throwable $throwable): Response
    {
        $e = FlattenException::createFromThrowable($throwable);
        $this->logException($throwable, sprintf('Uncaught PHP Exception %s: "%s" at %s line %s', $e->getClass(), $e->getMessage(), $e->getFile(), $e->getLine()));
        return $this->decoratedExceptionHandlerInterface->handleException($throwable);
    }

    /**
     * Checks if this handler (decorator) supports the given exception.
     *
     * Currently, it's configured to only "support" (and thus log) exceptions
     * that are instances of `TounafException`. This could be broadened if the decorator
     * is intended to log more types of exceptions.
     *
     * @param  \Throwable $throwable The exception or error to check.
     * @return bool True if the exception is an instance of `TounafException`, false otherwise.
     *              Note: For a decorator, `supportsException` often mirrors the decorated handler's
     *              `supportsException` or is broader if it's a general-purpose logger.
     *              The current implementation suggests it only activates for `TounafException`.
     */
    public function supportsException(\Throwable $throwable): bool
    {
        // This support check determines if this logger decorator should be active for the exception.
        // If it returns true, its handleException (which logs) is called.
        // It then delegates to the wrapped handler's handleException.
        // The wrapped handler's supportsException would have already been checked by the registry.
        return $this->decoratedExceptionHandlerInterface->supportsException($throwable);
    }

    /**
     * Sets the decorated (wrapped) exception handler instance.
     *
     * This method is part of the `DecoratorExceptionHandlerInterface` contract
     * and is used by the `ExceptionRegistry` to inject the primary handler
     * that this logger will wrap.
     *
     * @param ExceptionHandlerInterface $decoratedExceptionHandlerInterface The exception handler to be decorated.
     * @return void
     */
    public function decoratesHandler(ExceptionHandlerInterface $decoratedExceptionHandlerInterface): void
    {
        $this->decoratedExceptionHandlerInterface = $decoratedExceptionHandlerInterface;
    }

    /**
     * Logs the exception details.
     *
     * It logs with CRITICAL level for non-HttpExceptionInterface exceptions and
     * ERROR level for HttpExceptionInterface instances.
     *
     * @param \Throwable $exception The exception to log.
     * @param string     $message   The main log message.
     * @return void
     */
    protected function logException(\Throwable $exception, string $message): void
    {
        if (!$exception instanceof HttpExceptionInterface) {
            $this->logger->critical(
                $message,
                ['exception' => $exception]
            );
        } else {
            $this->logger->error(
                $message,
                ['exception' => $exception]
            );
        }
    }

}
